const KAMUS: Record<Bahasa, Record<Kunci, string>> = { id: ID as Record<Kunci, string>, en: EN };

/** Ambil teks sesuai bahasa, dengan penggantian {nama} dan sejenisnya. */
export function kamus(b: Bahasa) {
  return (kunci: Kunci, isi?: Record<string, string | number>) => {
    let teks = KAMUS[b][kunci];
    if (isi) for (const [k, v] of Object.entries(isi)) teks = teks.replace(`{${k}}`, String(v));
    return teks;
  };
}
