export const KUNCI_BAHASA = "infotrip:bahasa";

/** Lokal untuk tanggal dan jam, mengikuti bahasa yang dipilih di HP ini. */
export const lokal = () => (baca<string>(KUNCI_BAHASA) === "en" ? "en-GB" : "id-ID");

export function useBahasa(): Bahasa {
  const v = useSimpan<string>(KUNCI_BAHASA);
  return v === "en" ? "en" : "id";
}

export function gantiBahasa(b: Bahasa) {
  tulis(KUNCI_BAHASA, b);
}

